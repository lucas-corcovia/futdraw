import 'package:flutter/material.dart';

class ThemeColorSet {
  final Color primary;
  final Color secondary;
  final Color label;
  final Color thumb;
  final Color overlay;
  final Color selected;

  const ThemeColorSet({
    required this.primary,
    required this.secondary,
    required this.label,
    required this.thumb,
    required this.overlay,
    required this.selected,
  });
}
